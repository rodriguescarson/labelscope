def _card(key: str, value: str, cls: str = "") -> str:
    return (
        f'<div class="card"><div class="k">{html.escape(key)}</div>'
        f'<div class="v {cls}">{html.escape(str(value))}</div></div>'
    )


def _table(rows: Sequence[Dict], columns: Sequence[str], limit: int = 40) -> str:
    head = "".join(f"<th>{html.escape(c)}</th>" for c in columns)
    body = []
    for row in rows[:limit]:
        cells = []
        for column in columns:
            value = row.get(column, "")
            if isinstance(value, float):
                cells.append(f'<td class="num">{value:.4g}</td>')
            elif isinstance(value, int):
                cells.append(f'<td class="num">{value}</td>')
            else:
                cells.append(f"<td>{html.escape(str(value))}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f'<div class="scroll"><table><thead><tr>{head}</tr></thead><tbody>{"".join(body)}</tbody></table></div>'


def write_html(
    title: str,
    subtitle: str,
    headline: Sequence[tuple],
    sections: Sequence[tuple],
    path: str,
) -> None:
    """``headline`` is [(key, value, css_class)]; ``sections`` is
    [(heading, prose, rows, columns)]."""
    parts = [
        "<!doctype html><meta charset='utf-8'>",
        f"<title>{html.escape(title)}</title>",
        f"<style>{_CSS}</style>",
        f"<h1>{html.escape(title)}</h1>",
        f"<p class='sub'>{html.escape(subtitle)}</p>",
        '<div class="cards">'
        + "".join(_card(k, v, c) for k, v, c in headline)
        + "</div>",
    ]
    for heading, prose, rows, columns in sections:
        parts.append(f"<h2>{html.escape(heading)}</h2>")
        if prose:
            parts.append(f"<p>{prose}</p>")
        if rows:
            parts.append(_table(rows, columns))
    parts.append(
        "<footer>Generated by "
        "<a href='https://github.com/rodriguescarson/labelscope'>labelscope</a>"
        " — MIT licensed.</footer>"
    )
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as handle:
        handle.write("\n".join(parts))
