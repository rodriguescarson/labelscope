"""CSV and single-file HTML reporting."""
from __future__ import annotations

import csv
import html
import json
import os
from typing import Dict, List, Sequence


def flatten(record: Dict, prefix: str = "") -> Dict:
    """Flatten one nested metric record into a single CSV row."""
    flat: Dict = {}
    for key, value in record.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            if all(isinstance(k, int) for k in value):     # e.g. value_fractions
                for k, v in value.items():
                    flat[f"{name}_{k}"] = v
            else:
                flat.update(flatten(value, prefix=f"{name}."))
        elif isinstance(value, (list, tuple)):
            flat[name] = json.dumps(list(value))
        else:
            flat[name] = value
    return flat


def write_csv(records: Sequence[Dict], path: str) -> None:
    rows = [flatten(r) for r in records]
    if not rows:
        open(path, "w").close()
        return
    fields: List[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def write_json(obj, path: str) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as handle:
        json.dump(obj, handle, indent=2, default=str)


